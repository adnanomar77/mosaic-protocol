"""Measure ECTC workloads and protocol-level byte decomposition.

This is an in-process serialized benchmark. It does not claim WAN throughput.
All capsules, receipts, closures, seals, and event records are generated by the
MOSAIC implementation itself; no synthetic byte values are used.
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics
import tempfile
import time
from pathlib import Path

from ccd_nexus import KeyPair
from mosaic import Member, MosaicProtocol
from mosaic.network import capsule_to_wire, closure_to_wire, receipt_to_wire, seal_to_wire
from testnet.events import EventLog


def encoded(value: object) -> int:
    return len(json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8"))


def make_protocol(resource_count: int, validator_count: int = 4) -> tuple[MosaicProtocol, KeyPair, dict[str, object]]:
    members = {f"w{i}": Member(f"w{i}", KeyPair.generate(), weight=1) for i in range(validator_count)}
    protocol = MosaicProtocol(members)
    client = KeyPair.generate()
    predecessors = {
        f"r{i}": protocol.create_resource(f"r{i}", owner=client.identity)
        for i in range(resource_count)
    }
    return protocol, client, predecessors


def event_bytes(path: Path) -> int:
    return path.stat().st_size if path.exists() else 0


def operation_bytes(capsule, closure, seal) -> dict[str, int]:
    capsule_payload = encoded(capsule_to_wire(capsule))
    receipt_payload = sum(encoded(receipt_to_wire(item)) for item in closure.receipts)
    closure_payload = encoded(closure_to_wire(closure))
    seal_payload = encoded(seal_to_wire(seal))
    frame_count = 1 + len(closure.receipts) + 1 + 1
    return {
        "capsule_bytes": capsule_payload,
        "witness_receipt_bytes": receipt_payload,
        "closure_wire_bytes": closure_payload,
        "closure_proof_bytes": max(0, closure_payload - receipt_payload),
        "closure_wrapper_bytes": max(0, closure_payload - receipt_payload),
        "state_seal_bytes": seal_payload,
        "gossip_overhead_bytes": frame_count * 4,
        "availability_bytes": 0,
        "message_count": frame_count,
    }


def summarize(mode: str, latencies: list[float], counters: dict[str, int], operations: int, wall: float, conflicts: int = 0, batch_size: int = 1, validator_count: int = 4) -> dict:
    protocol_bytes = sum(
        counters[key]
        for key in (
            "capsule_bytes",
            "witness_receipt_bytes",
            "closure_proof_bytes",
            "state_seal_bytes",
            "gossip_overhead_bytes",
            "event_log_bytes",
            "availability_bytes",
            "bundle_bytes",
        )
    )
    return {
        "mode": mode,
        "validators": validator_count,
        "operations": operations,
        "batch_size": batch_size,
        "contention": "disjoint" if mode in {"disjoint", "scaling"} else ("same-resource" if mode == "contended" else "disjoint-batched"),
        "latency_ms_p50": statistics.median(latencies),
        "latency_ms_p95": sorted(latencies)[max(0, int(len(latencies) * 0.95) - 1)],
        "wall_time_s": wall,
        "throughput_ops_s": operations / wall if wall else 0.0,
        "conflicts": conflicts,
        "messages": counters["message_count"],
        "capsule_bytes": counters["capsule_bytes"],
        "witness_receipt_bytes": counters["witness_receipt_bytes"],
        "closure_proof_bytes": counters["closure_proof_bytes"],
        "closure_wire_bytes": counters["closure_wire_bytes"],
        "closure_wrapper_bytes": counters["closure_wrapper_bytes"],
        "state_seal_bytes": counters["state_seal_bytes"],
        "gossip_overhead_bytes": counters["gossip_overhead_bytes"],
        "event_log_bytes": counters["event_log_bytes"],
        "availability_bytes": counters["availability_bytes"],
        "bundle_bytes": counters["bundle_bytes"],
        "protocol_bytes": protocol_bytes,
        "protocol_bytes_per_successful_operation": protocol_bytes / operations,
    }


def run_serial(mode: str, operations: int, root: Path, validator_count: int = 4) -> dict:
    protocol, client, predecessors = make_protocol(operations if mode in {"disjoint", "scaling"} else 1, validator_count)
    log_path = root / f"{mode}-v{validator_count}.jsonl"
    log = EventLog(log_path, "ectc-workload", "mosaic-ectc-workloads-v1")
    latencies: list[float] = []
    counters = {key: 0 for key in (
        "capsule_bytes", "witness_receipt_bytes", "closure_proof_bytes", "closure_wire_bytes", "closure_wrapper_bytes",
        "state_seal_bytes", "gossip_overhead_bytes", "event_log_bytes", "availability_bytes",
        "bundle_bytes", "message_count",
    )}
    started = time.perf_counter()
    for i in range(operations):
        resource = f"r{i}" if mode in {"disjoint", "scaling"} else "r0"
        predecessor = protocol.current_seals[resource]
        capsule = protocol.create_capsule(client=client, predecessor=predecessor, successor_root=f"{mode}-{i}")
        t0 = time.perf_counter_ns()
        closure = protocol.close(capsule)
        seal = protocol.apply(capsule, closure)
        latencies.append((time.perf_counter_ns() - t0) / 1_000_000)
        payload = operation_bytes(capsule, closure, seal)
        for key, value in payload.items():
            counters[key] += value
        before = event_bytes(log_path)
        log.append("transition_closed", "benchmark", capsule_id=capsule.capsule_id, closure_id=closure.proof_id, seal_id=seal.seal_id, resource=resource)
        counters["event_log_bytes"] += event_bytes(log_path) - before
    wall = time.perf_counter() - started
    result = summarize(mode, latencies, counters, operations, wall, validator_count=validator_count)
    result["event_log_verified"] = log.verify()
    return result


def run_batched(operations: int, batch_size: int, root: Path) -> dict:
    protocol, client, predecessors = make_protocol(operations)
    log_path = root / f"batch-{batch_size}.jsonl"
    log = EventLog(log_path, "ectc-workload", "mosaic-ectc-workloads-v1")
    latencies: list[float] = []
    counters = {key: 0 for key in (
        "capsule_bytes", "witness_receipt_bytes", "closure_proof_bytes", "closure_wire_bytes", "closure_wrapper_bytes",
        "state_seal_bytes", "gossip_overhead_bytes", "event_log_bytes", "availability_bytes",
        "bundle_bytes", "message_count",
    )}
    prepared = []
    started = time.perf_counter()
    for i in range(operations):
        predecessor = predecessors[f"r{i}"]
        capsule = protocol.create_capsule(client=client, predecessor=predecessor, successor_root=f"batch-{i}")
        closure = protocol.close(capsule)
        prepared.append((capsule, closure))
        # Object bytes are charged once per successful operation.
        capsule_payload = encoded(capsule_to_wire(capsule))
        receipt_payload = sum(encoded(receipt_to_wire(item)) for item in closure.receipts)
        closure_payload = encoded(closure_to_wire(closure))
        counters["capsule_bytes"] += capsule_payload
        counters["witness_receipt_bytes"] += receipt_payload
        counters["closure_wire_bytes"] += closure_payload
        counters["closure_proof_bytes"] += max(0, closure_payload - receipt_payload)
        counters["closure_wrapper_bytes"] += max(0, closure_payload - receipt_payload)
        counters["message_count"] += 1 + len(closure.receipts) + 1
    for offset in range(0, operations, batch_size):
        entries = tuple(prepared[offset : offset + batch_size])
        bundle_id = f"bundle-{batch_size}-{offset}"
        bundle = protocol.bundle_closure(bundle_id, tuple(closure for _, closure in entries))
        bundle_payload = {"bundle_id": bundle.bundle_id, "closure_ids": list(bundle.closure_ids), "proof_id": bundle.proof_id}
        counters["bundle_bytes"] += encoded(bundle_payload)
        t0 = time.perf_counter_ns()
        seals = protocol.apply_bundle(bundle, entries)
        elapsed = (time.perf_counter_ns() - t0) / 1_000_000
        per_op = elapsed / len(entries)
        latencies.extend([per_op] * len(entries))
        for seal in seals:
            counters["state_seal_bytes"] += encoded(seal_to_wire(seal))
            counters["gossip_overhead_bytes"] += 4
        before = event_bytes(log_path)
        log.append("bundle_closed", "benchmark", bundle_id=bundle_id, operations=len(entries), closure_ids=list(bundle.closure_ids))
        counters["event_log_bytes"] += event_bytes(log_path) - before
    wall = time.perf_counter() - started
    result = summarize("batched", latencies, counters, operations, wall, batch_size=batch_size)
    result["event_log_verified"] = log.verify()
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--operations", type=int, default=1000)
    parser.add_argument("--output", default="docs/mosaic_ectc_workloads.json")
    parser.add_argument("--csv", default="paper/ledger_submission/ectc_workloads.csv")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="mosaic-ectc-") as tmp:
        root = Path(tmp)
        rows = [run_serial("disjoint", args.operations, root), run_serial("contended", args.operations, root)]
        for batch_size in (1, 10, 100):
            rows.append(run_batched(args.operations, batch_size, root))
        scaling_operations = min(args.operations, 120)
        for validator_count in (4, 7, 10, 16):
            rows.append(run_serial("scaling", scaling_operations, root, validator_count=validator_count))
    Path(args.output).write_text(json.dumps({"scope": "in-process serialized workload; not WAN evidence", "results": rows}, indent=2) + "\n", encoding="utf-8")
    Path(args.csv).parent.mkdir(parents=True, exist_ok=True)
    with Path(args.csv).open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)
    print(json.dumps(rows, indent=2))


if __name__ == "__main__":
    main()
